  const noFp = mk({ chg: 99 }); t = await cmp(noFp, mk({ chg: 99, outs: [[31, 100000n], [32, 56000n]] })); chk('bump without change info', /NOTE  The output that got smaller .* is not marked as change/.test(t) && /plain fee bump/.test(t));
